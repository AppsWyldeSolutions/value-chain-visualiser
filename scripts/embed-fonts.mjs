// Regenerates packages/renderer/src/fonts.generated.ts: the @font-face rules
// for the renderer's fonts with each woff2 inlined as a data URI, so the
// renderer never fetches a font at runtime (Power BI visuals may not). The
// font files come from the @fontsource devDependencies, pinned by the lockfile.
// Run with: node scripts/embed-fonts.mjs   (--check verifies without writing)
import { readFile, writeFile, mkdir, copyFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const rootDir = path.resolve(fileURLToPath(import.meta.url), "../..");
const fontsourceDir = path.join(rootDir, "node_modules/@fontsource");
const rendererDir = path.join(rootDir, "packages/renderer");
const outFile = path.join(rendererDir, "src/fonts.generated.ts");
const licenseDir = path.join(rendererDir, "licenses");

// The faces docs/prototype/Main.dc.html actually uses, Latin subset only.
const FACES = [
  { pkg: "dm-sans", family: "DM Sans", weight: 400 },
  { pkg: "dm-sans", family: "DM Sans", weight: 500 },
  { pkg: "dm-sans", family: "DM Sans", weight: 700 },
  { pkg: "bricolage-grotesque", family: "Bricolage Grotesque", weight: 700 },
];

async function fontFace({ pkg, family, weight }) {
  const pkgDir = path.join(fontsourceDir, pkg);
  // <weight>.css lists every subset; take the range of the Latin block.
  const css = await readFile(path.join(pkgDir, `${weight}.css`), "utf8");
  const block = css.split(`/* ${pkg}-latin-${weight}-normal */`)[1] ?? "";
  const range = block.match(/unicode-range:\s*([^;]+);/);
  if (!range) throw new Error(`No Latin unicode-range in ${pkg} ${weight}.css`);
  const woff2 = await readFile(
    path.join(pkgDir, "files", `${pkg}-latin-${weight}-normal.woff2`),
  );
  return (
    `@font-face{font-family:'${family}';font-style:normal;font-display:swap;` +
    `font-weight:${weight};` +
    `src:url(data:font/woff2;base64,${woff2.toString("base64")}) format('woff2');` +
    `unicode-range:${range[1].trim()};}`
  );
}

async function generate() {
  const faces = await Promise.all(FACES.map(fontFace));
  return (
    "// Generated by scripts/embed-fonts.mjs. Do not edit by hand.\n" +
    "// DM Sans and Bricolage Grotesque are licensed under the SIL Open Font\n" +
    "// License 1.1; see packages/renderer/licenses.\n" +
    `export const fontFaceCss = ${JSON.stringify(faces.join(""))};\n`
  );
}

const source = await generate();
if (process.argv.includes("--check")) {
  const current = await readFile(outFile, "utf8").catch(() => "");
  if (current.replace(/\r\n/g, "\n") !== source) {
    console.error(
      "fonts.generated.ts is stale. Run: node scripts/embed-fonts.mjs",
    );
    process.exit(1);
  }
} else {
  await writeFile(outFile, source);
  await mkdir(licenseDir, { recursive: true });
  for (const pkg of new Set(FACES.map((face) => face.pkg))) {
    await copyFile(
      path.join(fontsourceDir, pkg, "LICENSE"),
      path.join(licenseDir, `${pkg}-OFL.txt`),
    );
  }
  console.log(`Wrote ${path.relative(rootDir, outFile)}`);
}
